// crypto.randomUUID exists only in secure contexts (HTTPS and localhost). Over plain HTTP, such as a dev server
// opened by its LAN address or a local build under its production name, it is undefined, and db.ts calls it as
// the module loads, so the app never started. getRandomValues works in every context.
export function uuid(): string {
  if (typeof crypto.randomUUID === 'function') return crypto.randomUUID()
  const b = crypto.getRandomValues(new Uint8Array(16))
  b[6] = (b[6] & 0x0f) | 0x40 // version 4
  b[8] = (b[8] & 0x3f) | 0x80 // RFC 9562 variant
  const h = Array.from(b, (x) => x.toString(16).padStart(2, '0')).join('')
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`
}
