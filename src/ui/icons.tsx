// Everything else comes from Lucide (lucide.dev, ISC), drawn at a 1.5 stroke, behind our own names so call sites
// stay as they are. The icons are square: `width` sets the size, `height` is accepted and ignored.
type Props = { width?: number | string; height?: number | string; className?: string; style?: CSSProperties }
const lucide =
  (Icon: LucideIcon, size = 24) =>
  ({ width, className, style }: Props) => <Icon size={width ?? size} strokeWidth={1.5} className={className} style={style} />

